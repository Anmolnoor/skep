@pytest.fixture()
def shelf(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """A seed shelf the test controls: the seed lane reads source and lock
    from the package, so no landing branch is needed."""
    root = tmp_path / "seeds"
    root.mkdir()
    monkeypatch.setattr(forge, "seed_tools_root", lambda: root)
    return root


def _seed(store: RunStore, shelf: Path, source: str, lock: str | None = None) -> None:
    (shelf / "pdf_tool.py").write_text(source, encoding="utf-8")
    if lock is not None:
        (shelf / "pdf_tool.lock.txt").write_text(lock, encoding="utf-8")
    if "pdf-tool" not in load_plugins(store):
        save_plugin(
            store,
            ForgedPlugin(
                "pdf-tool", "pdf_tool", "pdfs", "draft", "", "pdf_tool.py", "", "forge-pdf-tool",
                provenance="seed",
            ),
        )  # fmt: skip


class _Lanes:
    """Every forged_lane / forged_runner use, recorded; installs succeed by
    writing the venv's python into the staging dir unless told to fail."""

    def __init__(self, monkeypatch: pytest.MonkeyPatch, *, install_fails: bool = False) -> None:
        self.calls: list[tuple[list[str], tuple[str, ...]]] = []
        self.trials: list[tuple[str, tuple[str, ...]]] = []
        self.install_fails = install_fails
        monkeypatch.setattr(mcp_client, "forged_lane", self.lane)
        monkeypatch.setattr(mcp_client, "forged_runner", self.runner)

    def lane(self, argv: list[str], **kwargs: Any) -> subprocess.CompletedProcess[str]:
        if argv[-1].endswith("tool.py"):  # the runtime exchange (the cache refresh)
            self.trials.append(("runtime", tuple(kwargs["hosts"])))
            listing = {"tools": [{"name": "echo"}, {"name": "self_test"}]}
            out = json.dumps({"jsonrpc": "2.0", "id": 2, "result": listing})
            return subprocess.CompletedProcess(argv, 0, out + "\n", "")
        self.calls.append((argv, tuple(kwargs["hosts"])))
        if "venv" in argv:
            python = Path(argv[-1]) / "bin" / "python"
            python.parent.mkdir(parents=True, exist_ok=True)
            python.write_text("#!fake", encoding="utf-8")
        if "install" in argv and self.install_fails:
            return subprocess.CompletedProcess(argv, 1, "", "pypdf has no wheel (sdist only)")
        return subprocess.CompletedProcess(argv, 0, "", "")

    def runner(self, source: str, python: str, *, skep_home: Path, hosts: tuple[str, ...]) -> Any:
        self.trials.append((python, tuple(hosts)))

        def run(method: str, params: Mapping[str, object]) -> Mapping[str, object]:
            if method == "tools/list":
                return {"tools": [{"name": "echo"}, {"name": "self_test"}]}
            return {"content": "self_test passed"}

        return run


def _passing_stage_one(monkeypatch: pytest.MonkeyPatch) -> list[dict[str, Any]]:
    seen: list[dict[str, Any]] = []

    def trial(*_a: Any, **kwargs: Any) -> dict[str, Any]:
        seen.append(kwargs)
        return {
            "state": "completed",
            "output": 'FORGE_TRIAL {"ok": true, "tools": ["echo", "self_test"], "self_test": "ok"}',
        }

    monkeypatch.setattr(tools_module, "_forge_trial", trial)
    return seen


def _card(store: RunStore) -> dict[str, Any]:
    card = recorded_card("promote_tool", {"plugin_id": "pdf-tool"}, None, store)
    assert card is not None
    return card


def _promote(config: SupervisorConfig, store: RunStore, card: dict[str, Any] | None) -> Any:
    return execute_mutation(
        "promote_tool",
        {"plugin_id": "pdf-tool"},
        store=store,
        holder=ConfigHolder(config, store),
        runner=cast(Dispatcher, None),
        actor="test",
        card=card,
    )


def test_the_card_shows_the_triple_and_the_full_diff(config: SupervisorConfig, shelf: Path) -> None:
    store = RunStore(config.db_path)
    try:
        _seed(store, shelf, _DEPS_TOOL, _LOCK)
        card = _card(store)["forge"]
        assert card["source_sha256"] == sha256_text(_DEPS_TOOL)
        assert card["lock_sha256"] == sha256_text(_LOCK)
        assert card["approved_hosts"] == ["*.example.net", "api.example.org"]
        assert card["locked"][0].startswith("pypdf==5.1.0 sha256:")
        assert card["diff"].count("\n+") >= _DEPS_TOOL.count("\n")  # every line, new
        summary = card_summary("promote_tool", {"plugin_id": "pdf-tool"}, recorded=_card(store))
        assert summary["forge"]["source_sha256"] == card["source_sha256"]
        assert "*.example.net, api.example.org" in summary["risk"]
        assert card["source_sha256"][:12] in summary["risk"]
        # A tool that cannot be bound says so on its card.
        (shelf / "pdf_tool.lock.txt").unlink()
        assert "lock.txt" in _card(store)["forge"]["error"]
    finally:
        store.close()


def test_a_confirm_installs_only_what_its_card_showed(
    config: SupervisorConfig, shelf: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    store = RunStore(config.db_path)
    try:
        _seed(store, shelf, ECHO_SERVER_SOURCE)
        _passing_stage_one(monkeypatch)
        _Lanes(monkeypatch)
        with pytest.raises(ValueError, match="card"):
            _promote(config, store, None)
        card = _card(store)
        # One byte changed after the card was shown: nothing installs.
        _seed(store, shelf, ECHO_SERVER_SOURCE + "#")
        with pytest.raises(ValueError, match="changed since its card"):
            _promote(config, store, card)
        assert load_plugins(store)["pdf-tool"].state == "draft"
        assert "forge-pdf-tool" not in load_mcp_servers(store)
    finally:
        store.close()


def test_a_stdlib_tool_promotes_with_no_venv_and_one_offline_stage(
    config: SupervisorConfig, shelf: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    store = RunStore(config.db_path)
    try:
        _seed(store, shelf, ECHO_SERVER_SOURCE)
        stage_one = _passing_stage_one(monkeypatch)
        lanes = _Lanes(monkeypatch)
        promoted = _promote(config, store, _card(store))
        assert promoted["state"] == "active"
        assert lanes.calls == []  # no install lane at all
        # stage 1 only (no hosts), then the cache refresh on the runtime path
        assert lanes.trials == [(sys.executable, ()), ("runtime", ())]
        assert stage_one[0]["python"] == sys.executable
        assert not (config.home.parent / "tools" / ".venvs").exists()
        record = load_plugins(store)["pdf-tool"]
        assert record.source_sha256 == sha256_text(ECHO_SERVER_SOURCE)
        assert (record.lock_sha256, record.approved_hosts) == ("", ())
        assert record.trial is not None and record.trial["wall"]["offline"]["ok"] is True
        # Phase 06's cache is refreshed: the next turn's index names it.
        server = load_mcp_servers(store)["forge-pdf-tool"]
        assert cached_tools(store, server) is not None
    finally:
        store.close()


def test_a_locked_tool_installs_wheels_only_from_hashes_through_pypi(
    config: SupervisorConfig, shelf: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    store = RunStore(config.db_path)
    try:
        _seed(store, shelf, _DEPS_TOOL, _LOCK)
        stage_one = _passing_stage_one(monkeypatch)
        lanes = _Lanes(monkeypatch)
        _promote(config, store, _card(store))
        (venv_argv, venv_hosts), (install_argv, install_hosts) = lanes.calls
        assert venv_hosts == ()  # making the venv needs no network
        assert install_hosts == forge.PYPI_HOSTS
        assert "--require-hashes" in install_argv and "--no-config" in install_argv
        assert install_argv[install_argv.index("--only-binary") + 1] == ":all:"
        staged = venv_argv[-1]
        assert Path(staged).name.startswith(".staging-")
        # both stages ran the STAGED venv; stage 2 pinned to the card's hosts
        assert stage_one[0]["python"] == f"{staged}/bin/python"
        assert lanes.trials == [
            (f"{staged}/bin/python", ()),
            (f"{staged}/bin/python", ("*.example.net", "api.example.org")),
            ("runtime", ("*.example.net", "api.example.org")),  # the refresh: bound hosts
        ]
        record = load_plugins(store)["pdf-tool"]
        assert record.lock_sha256 == sha256_text(_LOCK)
        assert record.approved_hosts == ("*.example.net", "api.example.org")
        final = forge.venv_python(config.home.parent, "pdf-tool", record.lock_sha256)
        assert final.is_file() and not Path(staged).exists()
        assert load_mcp_servers(store)["forge-pdf-tool"].command[0] == str(final)
    finally:
        store.close()


def test_a_failed_install_or_trial_leaves_the_active_tool_untouched(
    config: SupervisorConfig, shelf: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    store = RunStore(config.db_path)
    try:
        _seed(store, shelf, ECHO_SERVER_SOURCE)
        _passing_stage_one(monkeypatch)
        _Lanes(monkeypatch)
        _promote(config, store, _card(store))
        before = load_plugins(store)["pdf-tool"]
        installed = config.home.parent / "tools" / "pdf-tool.py"
        # v2 declares deps whose only distribution is an sdist: fail closed.
        _seed(store, shelf, _DEPS_TOOL, _LOCK)
        _Lanes(monkeypatch, install_fails=True)
        with pytest.raises(ValueError, match=r"sdist.*active copy keeps running"):
            _promote(config, store, _card(store))
        after = load_plugins(store)["pdf-tool"]
        assert (after.state, after.source_sha256, after.lock_sha256) == (
            "active", before.source_sha256, "",
        )  # fmt: skip
        assert installed.read_text(encoding="utf-8") == ECHO_SERVER_SOURCE
        venvs = config.home.parent / "tools" / ".venvs" / "pdf-tool"
        assert list(venvs.iterdir()) == []  # the staging venv is gone
        # The wall's stage 2 failing is the same: nothing changes.
        lanes = _Lanes(monkeypatch)

        def egress_fails(source: str, python: str, *, skep_home: Path, hosts: Any) -> Any:
            lanes.trials.append((python, tuple(hosts)))

            def run(method: str, params: Mapping[str, object]) -> Mapping[str, object]:
                if method == "tools/list":
                    return {"tools": [{"name": "echo"}, {"name": "self_test"}]}
                return {"content": "upstream refused", "isError": bool(hosts)}

            return run

        monkeypatch.setattr(mcp_client, "forged_runner", egress_fails)
        with pytest.raises(ValueError, match="egress pinned to"):
            _promote(config, store, _card(store))
        assert load_plugins(store)["pdf-tool"].source_sha256 == before.source_sha256
        assert list(venvs.iterdir()) == []
    finally:
        store.close()


def test_a_legacy_active_tool_can_be_promoted_again(
    config: SupervisorConfig, shelf: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """An active record from before the binding is refused at runtime; the
    verb that fixes it must not answer 'already active'."""
    import dataclasses

    store = RunStore(config.db_path)
    try:
        _seed(store, shelf, ECHO_SERVER_SOURCE)
        record = load_plugins(store)["pdf-tool"]
        save_plugin(store, dataclasses.replace(record, state="active"))
        forge.install_source(config, "pdf-tool", ECHO_SERVER_SOURCE)
        _passing_stage_one(monkeypatch)
        _Lanes(monkeypatch)
        promoted = _promote(config, store, _card(store))
        assert promoted.get("note") != "already active"
        assert load_plugins(store)["pdf-tool"].source_sha256 == sha256_text(ECHO_SERVER_SOURCE)
    finally:
        store.close()


