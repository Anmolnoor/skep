_HASH_B = "b" * 64
_LOCK = f"""# This file was autogenerated by uv via the following command:
#    uv pip compile --generate-hashes --only-binary :all: -
pypdf==5.1.0 \\
    --hash=sha256:{_HASH_A} \\
    --hash=sha256:{_HASH_B}
    # via -r -
typing-extensions==4.12.2 ; python_version < "3.11" \\
    --hash=sha256:{_HASH_A}
"""
