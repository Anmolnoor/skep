"""Phase 07 (7.2): opt-in locked PEP 723 deps, the card binding, two stages.

A forged tool stays one stdlib-only file unless it opts in: a PEP 723
`# /// script` block names its dependencies, a `# skep-hosts:` line names
the hosts it may reach. A tool that declares dependencies ships a hash lock
beside it (`<tool>.lock.txt`, `uv pip compile --generate-hashes` output);
skep installs that lock wheels-only (`--only-binary :all:`) with
`--require-hashes`, in the forged-tool wall with egress pinned to PyPI — no
sdist build code ever runs. The promotion card shows `(source_sha256,
lock_sha256, approved_hosts)` and the full source diff, and the confirm
installs only that triple (I6). The trial runs twice behind the runtime
wall: offline and deny-all, then — only with approved hosts — egress pinned
to them (I2). A failure anywhere leaves the active tool as it was.
"""

