def _wheel(links: Path) -> Path:
    wheel = links / "demo_pkg-0.1-py3-none-any.whl"
    files = {
        "demo_pkg/__init__.py": "VALUE = 42\n",
        "demo_pkg-0.1.dist-info/METADATA": "Metadata-Version: 2.1\nName: demo-pkg\nVersion: 0.1\n",
        "demo_pkg-0.1.dist-info/WHEEL": "Wheel-Version: 1.0\nGenerator: t\n"
        "Root-Is-Purelib: true\nTag: py3-none-any\n",
    }
    record = "".join(f"{name},,\n" for name in [*files, "demo_pkg-0.1.dist-info/RECORD"])
    with zipfile.ZipFile(wheel, "w") as archive:
        for name, content in files.items():
            archive.writestr(name, content)
        archive.writestr("demo_pkg-0.1.dist-info/RECORD", record)
    return wheel


def _trap_sdist(links: Path, marker: Path) -> Path:
    """An sdist whose build would drop ``marker``: proof no build ran."""
    sdist = links / "trap_pkg-0.1.tar.gz"
    members = {
        "trap_pkg-0.1/PKG-INFO": "Metadata-Version: 2.1\nName: trap-pkg\nVersion: 0.1\n",
        "trap_pkg-0.1/setup.py": f"open({str(marker)!r}, 'w').write('ran')\n",
    }
    with tarfile.open(sdist, "w:gz") as archive:
        for name, content in members.items():
            data = content.encode()
            info = tarfile.TarInfo(name)
            info.size = len(data)
            archive.addfile(info, io.BytesIO(data))
    return sdist


@needs_wall
@pytest.mark.skipif(shutil.which("uv") is None, reason="uv is not on PATH")
def test_the_install_command_takes_hashed_wheels_and_refuses_the_rest(tmp_path: Path) -> None:
    """The production install command, in the real wall, against a local
    find-links dir instead of PyPI (``--offline``, no network): a hashed
    wheel installs and imports from the relocated venv behind the runtime
    wall; a wrong hash refuses; an sdist-only package refuses and its build
    code never runs."""
    home = tmp_path / "skep"
    (home / "supervisor").mkdir(parents=True)
    root = home / "tools" / ".venvs" / "demo"
    root.mkdir(parents=True)
    source = tmp_path / "links"
    source.mkdir()
    marker = tmp_path / "SDIST_BUILD_RAN"
    sha = {path.name: hashlib.sha256(path.read_bytes()).hexdigest()
           for path in (_wheel(source), _trap_sdist(source, marker))}  # fmt: skip
    uv = str(shutil.which("uv"))

    def install(lock_line: str) -> tuple[int, Path]:
        staging = Path(tempfile.mkdtemp(prefix=".staging-", dir=root))
        with tempfile.TemporaryDirectory() as tmp:
            workspace = Path(tmp)
            links = workspace / "links"  # inside the wall: the strict reads see it
            shutil.copytree(source, links)
            (workspace / "lock.txt").write_text(lock_line + "\n", encoding="utf-8")

            def lane(argv: list[str]) -> subprocess.CompletedProcess[str]:
                return mcp_client.forged_lane(
                    argv, skep_home=home, hosts=(), workspace=workspace, writable=(staging,),
                    timeout=120,
                )  # fmt: skip

            assert lane(forge.venv_command(uv, staging)).returncode == 0
            command = forge.install_command(uv, staging / "bin" / "python", workspace / "lock.txt")
            proc = lane([*command, "--offline", "--find-links", str(links)])
        return proc.returncode, staging

    code, staging = install(f"demo-pkg==0.1 --hash=sha256:{sha['demo_pkg-0.1-py3-none-any.whl']}")
    assert code == 0
    final = staging.rename(root / "final")
    probe = (
        "import sys, json, demo_pkg\nfor line in sys.stdin:\n    msg = json.loads(line)\n"
        "    print(json.dumps({'jsonrpc': '2.0', 'id': msg['id'], "
        "'result': {'value': demo_pkg.VALUE}}), flush=True)\n"
    )
    reply = mcp_client.forged_runner(probe, str(final / "bin" / "python"), skep_home=home, hosts=())
    assert reply("tools/list", {}) == {"value": 42}
    assert install(f"demo-pkg==0.1 --hash=sha256:{'a' * 64}")[0] != 0
    assert install(f"trap-pkg==0.1 --hash=sha256:{sha['trap_pkg-0.1.tar.gz']}")[0] != 0
    assert not marker.exists()


